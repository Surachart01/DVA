def validate_plan(text: str, week: int) -> None:
    found = [int(value) for value in re.findall(r"^## (\d+)\.", text, re.M)]
    if found != list(range(1, 11)):
        raise ValueError(f"W{week:02}: section sequence is {found}")
    time = metadata(text).get("เวลา", "")
    if "180 นาที" not in time or "120 นาที" not in time:
        raise ValueError(f"W{week:02}: missing 180/120 minute schedule")
    if re.search(r"\b(?:for|def)\s+\w+|Matplotlib|Challenge", text):
        raise ValueError(f"W{week:02}: outdated content leaked into plan")
    for day, required in [("วันจันทร์", 180), ("วันพฤหัสบดี", 120)]:
        daily = text.split(f"### {day}", 1)[1].split("**ลำดับ", 1)[0]
        durations = [int(value) for value in re.findall(r"\| (\d+) นาที \|", daily)]
        if sum(durations) != required:
            raise ValueError(f"W{week:02}: {day} totals {sum(durations)}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[2])
    parser.add_argument("--backup", type=Path)
    parser.add_argument("--check", action="store_true", help="Check current files without writing")
    args = parser.parse_args()
    root = args.root.resolve()
    backup = args.backup or root / BACKUP_NAME
    ready = root / READY_NAME
    plan_dir = ready / "แผนรายสัปดาห์"
    spec_dir = root / "dva-slides/lesson-specs"
    week_one = next(plan_dir.glob("สัปดาห์ที่01_*.md"))
    week_one_before = hashlib.sha256(week_one.read_bytes()).hexdigest()
    special = {item["week"]: item for item in json.loads((spec_dir / "special-weeks.json").read_text())}
    expected = {}
    with zipfile.ZipFile(backup) as archive:
        for week in range(2, 16):
            entry = next(name for name in archive.namelist()
                         if name.startswith(READY_NAME + "/แผนรายสัปดาห์/")
                         and f"/สัปดาห์ที่{week:02}_" in name and name.endswith(".md"))
            original = archive.read(entry).decode("utf-8-sig")
            spec = special[week] if week in SPECIAL_WEEKS else json.loads(
                (spec_dir / f"week{week:02}.json").read_text())
            if week in NORMAL_WEEKS:
                for filename in spec["files"]:
                    if not (ready / "ชุดข้อมูล" / filename).is_file():
                        raise FileNotFoundError(filename)
            plan = root / entry
            result = render_plan(week, spec, original)
            validate_plan(result, week)
            expected[plan] = result
    # Validate every result before modifying any plan.
    for plan, result in expected.items():
        if args.check:
            if plan.read_text() != result:
                raise ValueError(f"Out of sync: {plan.name}")
        else:
            plan.write_text(result)
    if hashlib.sha256(week_one.read_bytes()).hexdigest() != week_one_before:
        raise ValueError("Week one changed")
    for week in range(1, 16):
        plan = next(plan_dir.glob(f"สัปดาห์ที่{week:02}_*.md"))
        time = metadata(plan.read_text()).get("เวลา", "")
        if "180 นาที" not in time or "120 นาที" not in time:
            raise ValueError(f"W{week:02}: cannot verify five teaching hours")
    action = "ตรวจ" if args.check else "ปรับ"
    print(f"{action}ครบ 14 แผน: ส่วนที่ 1–10 ครบ; จันทร์ 180 + พฤหัสบดี 120 นาที")
    print("รวมทั้ง 15 สัปดาห์ 75 ชั่วโมง; สัปดาห์ที่ 1 ไม่เปลี่ยน; คะแนนและเกณฑ์เดิมแยกจากตัวอย่างฝึก")


if __name__ == "__main__":
    main()
