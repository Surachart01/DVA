def activity_table(rows: list[tuple[str, str, str, int | str]]) -> str:
    text = "| ขั้น | กิจกรรมผู้สอน | กิจกรรมผู้เรียน | เวลา |\n|---|---|---|---|"
    for stage, teacher, student, minutes in rows:
        duration = f"{minutes} นาที" if isinstance(minutes, int) else minutes
        text += f"\n| {stage} | {teacher} | {student} | {duration} |"
    total = sum(row[3] for row in rows if isinstance(row[3], int))
    return text + f"\n| **รวมเวลาคาบ** | | | **{total} นาที** |"


