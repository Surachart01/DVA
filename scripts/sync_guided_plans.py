TICK = chr(96)


def inline(value: str) -> str:
    return TICK + value.replace("|", r"\|").replace("\n", " ") + TICK


def bullet_list(values: list[str]) -> str:
    return "\n".join("- " + value for value in values)


def numbered(values: list[str]) -> str:
    return "\n".join(f"{i}. {value}" for i, value in enumerate(values, 1))


def section(text: str, number: int) -> str:
    match = re.search(
        rf"^## {number}\.[^\n]*\n(.*?)(?=^## {number + 1}\.|^# |\Z)",
        text, re.M | re.S,
    )
    return match.group(1).strip() if match else ""


def heading_body(text: str, heading: str) -> str:
    lines = text.splitlines()
    for i, line in enumerate(lines):
        if line.strip() == heading:
            body = []
            for following in lines[i + 1:]:
                if following.startswith("#"):
                    break
                body.append(following)
            return "\n".join(body).strip()
    return ""


def metadata(text: str) -> dict[str, str]:
    result = {}
    for line in text.split("## 1.", 1)[0].splitlines():
        if line.startswith("|"):
            cells = [cell.strip() for cell in line.strip("|").split("|")]
            if len(cells) == 2 and cells[0] not in {"รายการ", "---"}:
                result[cells[0]] = cells[1]
    return result


def method_names(spec: dict) -> list[str]:
    result = []
    for step in spec["steps"]:
        for node in ast.walk(ast.parse(step["code"])):
            if isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute):
                name = node.func.attr + "()"
                if name not in result:
                    result.append(name)
    return result


def exports(spec: dict) -> list[str]:
    result = []
    for step in spec["steps"]:
        for node in ast.walk(ast.parse(step["code"])):
            if (isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute)
                    and node.func.attr in {"to_csv", "write_html"} and node.args
                    and isinstance(node.args[0], ast.Constant)
                    and isinstance(node.args[0].value, str)):
                if node.args[0].value not in result:
                    result.append(node.args[0].value)
    return result


