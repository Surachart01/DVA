def _code(c):
    return '`' + c.replace('|', r'\|') + '`'


def _steps_table(spec, day):
    rows = ['| ขั้น | หัวข้อและคำสั่ง | ผลที่ต้องตรวจ/อธิบาย |', '|---|---|---|']
    for i, st in enumerate(spec['steps'], 1):
        if st['day'] == day:
            rows.append(f"| {i} | {st['title']}: {_code(st['code'])} | {st['checkpoint']} |")
    return '\n'.join(rows)


def _table(rows):
    out = ['| ขั้น | กิจกรรมผู้สอน | กิจกรรมผู้เรียน | เวลา |', '|---|---|---|---|']
    out += [f'| {a} | {b} | {c} | {d} นาที |' for a, b, c, d in rows]
    out.append(f"| **รวมเวลาคาบ** | | | **{sum(r[3] for r in rows)} นาที** |")
    return '\n'.join(out)


